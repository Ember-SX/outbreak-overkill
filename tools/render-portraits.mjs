// Renders every operative outfit from the procedural portrait renderer to an image file in
// assets/portraits/<operative>/<outfit>.webp and rewrites assets/portraits/manifest.js.
//
//   npm run portraits                 all outfits, 768 x 1024 WebP
//   npm run portraits -- --keep       only outfits that have no file yet (keeps commissioned art)
//   npm run portraits -- rin          one operative
//
// These files are the baseline set. To use commissioned illustrations, drop them in with the
// same names (or point manifest.js at other files) and the game picks them up.
//
// Set PW_CHROMIUM=/path/to/chromium to use a specific browser binary.
import { chromium } from 'playwright';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { existsSync, mkdirSync, writeFileSync, readdirSync } from 'node:fs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets', 'portraits');
const args = process.argv.slice(2);
const keep = args.includes('--keep');
const only = args.find((a) => !a.startsWith('--'));
const W = 768, H = 1024;

const browser = await chromium.launch(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {});
const page = await browser.newPage();
page.on('pageerror', (e) => console.error('page error:', e.message));
await page.goto(pathToFileURL(join(root, 'index.html')).href);
await page.waitForFunction(() => window.OO && OO.Characters && OO.SKINS);

const list = await page.evaluate(() => Object.keys(OO.SKINS).flatMap((c) => OO.SKINS[c].map((s) => [c, s.id])));
let written = 0;
for (const [charId, skinId] of list) {
  if (only && charId !== only) continue;
  const file = join(outDir, charId, skinId + '.webp');
  if (keep && existsSync(file)) continue;
  const dataUrl = await page.evaluate(({ charId, skinId, W, H }) => {
    const c = document.createElement('canvas');
    c.width = W; c.height = H;
    const x = c.getContext('2d');
    x.scale(W / OO.Characters.PW, H / OO.Characters.PH);
    OO.Characters.drawPortrait(x, charId, skinId);
    return c.toDataURL('image/webp', 0.92);
  }, { charId, skinId, W, H });
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, Buffer.from(dataUrl.split(',')[1], 'base64'));
  written++;
}
await browser.close();

// Manifest: every image file present under assets/portraits/<operative>/
const files = {};
for (const charId of readdirSync(outDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  for (const f of readdirSync(join(outDir, charId)).sort()) {
    const m = f.match(/^(.+)\.(webp|png|jpe?g|avif)$/i);
    if (m) files[charId + '/' + m[1]] = charId + '/' + f;
  }
}
const body = `// Portrait image assets for the menu dossier and the Armory wardrobe (see js/portraits.js).
// Generated by tools/render-portraits.mjs. Edit by hand to point at commissioned art; any outfit
// without an entry (or whose file fails to load) falls back to the procedural portrait.
window.OO = window.OO || {};
OO.PORTRAIT_MANIFEST = {
  base: 'assets/portraits/',
  files: ${JSON.stringify(files, null, 4).replace(/\n}/, '\n  }').replace(/\n    /g, '\n    ')},
  // Optional vertical crop focus per outfit, 0 = top, 1 = bottom (default: centred).
  focus: {},
};
`;
writeFileSync(join(outDir, 'manifest.js'), body);
console.log(`Wrote ${written} portrait(s); manifest lists ${Object.keys(files).length}.`);
